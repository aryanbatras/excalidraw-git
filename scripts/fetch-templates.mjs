// Pulls real, interview-grade Excalidraw scenes into the gallery public dir.
//
//   node scripts/fetch-templates.mjs
//
// Attribution: scenes originate from
//   https://github.com/Prakash-sa/system-design-ultimatum
// (curated system-design interview diagrams; no formal license — see
// public/templates/README.md). Only the JSON scenes are copied; no images.
//
import { mkdir, writeFile, readFile } from "node:fs/promises";
import { join, dirname } from "node:path";
import { fileURLToPath } from "node:url";

const ROOT = join(dirname(fileURLToPath(import.meta.url)), "..");
const SRC = "https://raw.githubusercontent.com/Prakash-sa/system-design-ultimatum/main/";

// source path (in upstream repo) -> target file under public/templates/
const MAP = {
  "🧩 1. Foundational(Introductory) Design/Load Balancer.excalidraw":
    "system-design/load-balancer.excalidraw",
  "🧩 1. Foundational(Introductory) Design/Tiny URL.excalidraw":
    "system-design/url-shortener.excalidraw",
  "🧩 1. Foundational(Introductory) Design/Web Crawler.excalidraw":
    "system-design/web-crawler.excalidraw",
  "💬 3. Social & Communication Systems/Chat System(Messaging).excalidraw":
    "system-design/chat-messaging.excalidraw",
  "🧩 1. Foundational(Introductory) Design/Redis.excalidraw":
    "system-design/redis-cache.excalidraw",
  "🧩 1. Foundational(Introductory) Design/Database Strategies.excalidraw":
    "uml-er/database-strategies.excalidraw",
  "🧠 7. Analytics, Streaming, and Data Pipelines/Ad Click Aggregator.excalidraw":
    "workflows/ad-click-aggregator.excalidraw",
  "🧠 7. Analytics, Streaming, and Data Pipelines/Log Ingestion Service.excalidraw":
    "workflows/log-ingestion.excalidraw",
  "🧰 9. DevOps-Cloud-SaaS Infrastructure/Distributed Job Scheduler (Airflow, Temporal, Celery).excalidraw":
    "workflows/job-scheduler.excalidraw",
  "🧩 1. Foundational(Introductory) Design/Data Structure.excalidraw":
    "algorithms/advanced-data-structures.excalidraw",
};

let changed = 0;
for (const [src, target] of Object.entries(MAP)) {
  const res = await fetch(SRC + encodeURIComponent(src));
  if (!res.ok) {
    console.error(`SKIP ${src}: HTTP ${res.status}`);
    continue;
  }
  const scene = await res.text();
  const parsed = JSON.parse(scene); // fail loudly if upstream is LFS pointer or malformed
  if (!Array.isArray(parsed.elements) || parsed.elements.length === 0) {
    console.error(`SKIP ${src}: ${parsed.elements.length} elements (LFS pointer?)`);
    continue;
  }
  const out = join(ROOT, "public/templates", target);
  await mkdir(dirname(out), { recursive: true });
  await writeFile(out, scene);
  changed++;
  console.log(`ok   ${target} (${parsed.elements.length} elements)`);
}

// provenance for attribution
const readme = `# Template gallery provenance

Each template lives as a plain \`.excalidraw\` JSON scene under this directory and
gets a 400×300 WebP preview in \`_thumbs/\` (generated by
\`scripts/generate-thumbs.mjs\`).

The following scenes were adopted (JSON only, no embedded media) from the
curated interview-prep collection
[Prakash-sa/system-design-ultimatum](https://github.com/Prakash-sa/system-design-ultimatum):

| App template | Upstream scene |
| --- | --- |
${Object.entries(MAP)
  .map(
    ([src, target]) =>
      `| \`${target.replace(/\.excalidraw$/, "")}\` | \`${src.replace(/\.excalidraw$/, "")}\` |`,
  )
  .join("\n")}

That repository carries no formal license (study notes). These copies are for
personal interview preparation only — if this app is ever published, replace or
relicense these scenes first.

Remaining scenes are generated in-repo by \`scripts/build-custom-templates.mjs\`.
`;
await writeFile(join(ROOT, "public/templates", "README.md"), readme);

console.log(`${changed}/${Object.keys(MAP).length} adopted; provenance README written`);
